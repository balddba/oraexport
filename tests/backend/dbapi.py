"""Test-only Oracle DB-API recorder; no alternate database engine is used.

This deliberately supports only the metadata SQL used by metadata operations. It checks
basic constraints and transaction rollback, but does not simulate Oracle row locks,
DDL, isolation, driver types, or query planning. Live tests cover remote behavior.
"""

import operator
import re
from copy import deepcopy
from typing import TypeVar

import oracledb
from pydantic import BaseModel

from oraexport.migrations import schema_statements

TOKEN = re.compile(r"\s*(:\w+|<>|>=|<=|=|>|<|\(|\)|,|'(?:[^']|'')*'|\d+|\w+)")


class Predicate:
    """Evaluate the small bound predicate grammar generated by metadata queries.

    Provides recursive-descent parsing and evaluation for SQL WHERE expressions
    emitted by the metadata repository queries, supporting equality, inequality,
    null checks, in-lists, conjunctions, and disjunctions.
    """

    def __init__(self, expression, binds, row):
        """Tokenize a static SQL fragment without executing arbitrary Python.

        Args:
            expression (str): SQL WHERE expression fragment to evaluate.
            binds (dict[str, Any]): Bound query parameters mapped by parameter name.
            row (dict[str, Any]): Current database table row represented as a dictionary.

        Raises:
            AssertionError: If expression contains unsupported SQL tokens.
        """
        # Tokenize the SQL fragment using regex into recognized SQL symbols and literals
        self.tokens = []
        position = 0
        while position < len(expression):
            match = TOKEN.match(expression, position)
            if not match:
                raise AssertionError(f"Unsupported test SQL predicate: {expression}")
            self.tokens.append(match[1])
            position = match.end()
        # Initialize parser cursor and store bound inputs
        self.position = 0
        self.binds = binds
        self.row = row

    def peek(self, token):
        """Check the next token without consuming it.

        Args:
            token (str): Expected uppercase token representation.

        Returns:
            bool: True if the next token matches token case-insensitively, False otherwise.
        """
        # Look ahead one token in the token stream without advancing the cursor position
        return self.position < len(self.tokens) and self.tokens[self.position].upper() == token

    def take(self, token=None):
        """Consume a token and reject malformed or unsupported predicates.

        Args:
            token (str | None): Optional expected token value for assertion validation.

        Returns:
            str: The consumed token string.

        Raises:
            AssertionError: If token is provided and does not match the consumed token.
        """
        # Consume the next token and advance the parser cursor
        value = self.tokens[self.position]
        self.position += 1
        if token is not None:
            assert value.upper() == token, (value, token)
        return value

    def value(self):
        """Resolve a column, bind parameter, numeric literal, or SQL NULL.

        Returns:
            Any: The evaluated literal value, bind parameter value, or row column value.

        Raises:
            AssertionError: If the token represents an unrecognized column name.
        """
        # Consume and evaluate the atomic operand value
        token = self.take()
        if token.startswith(":"):
            # Lookup named bind parameter without leading colon
            return self.binds[token[1:]]
        if token.startswith("'"):
            # Unescape SQL single quotes in string literal
            return token[1:-1].replace("''", "'")
        if token.upper() == "NULL":
            # SQL NULL maps to Python None
            return None
        if token.isdigit():
            # Parse integer literal
            return int(token)
        # Look up column name directly against current row dictionary
        assert token in self.row, f"Unknown test SQL column: {token}"
        return self.row[token]

    def atom(self):
        """Evaluate a grouped predicate, null test, membership, or comparison.

        Returns:
            bool: Boolean evaluation result of the atomic predicate.

        Raises:
            AssertionError: If an unsupported comparison operator is encountered.
        """
        # Parenthesized sub-expression
        if self.peek("("):
            self.take("(")
            result = self.disjunction()
            self.take(")")
            return result
        # Left-hand side operand evaluation
        left = self.value()
        # Null check: IS [NOT] NULL
        if self.peek("IS"):
            self.take("IS")
            negate = self.peek("NOT")
            if negate:
                self.take("NOT")
            self.take("NULL")
            return left is not None if negate else left is None
        # Membership test: IN (val1, val2, ...)
        if self.peek("IN"):
            self.take("IN")
            self.take("(")
            values = [self.value()]
            while self.peek(","):
                self.take(",")
                values.append(self.value())
            self.take(")")
            return left is not None and left in [value for value in values if value is not None]
        # Binary comparison operator
        op = self.take()
        right = self.value()
        comparisons = {"=": operator.eq, "<>": operator.ne, ">": operator.gt}
        comparisons["<"] = operator.lt
        comparisons[">="] = operator.ge
        comparisons["<="] = operator.le
        assert op in comparisons, f"Unsupported test SQL operator: {op}"
        return left is not None and right is not None and comparisons[op](left, right)

    def conjunction(self):
        """Evaluate AND with comparison precedence and consume both operands.

        Returns:
            bool: Boolean result of chaining all contiguous AND operands.
        """
        # Evaluate left atom then greedily consume AND operators
        result = self.atom()
        while self.peek("AND"):
            self.take("AND")
            right = self.atom()
            result = result and right
        return result

    def disjunction(self):
        """Evaluate OR after each conjunction.

        Returns:
            bool: Boolean result of chaining all contiguous OR operands.
        """
        # Evaluate conjunction then greedily consume OR operators
        result = self.conjunction()
        while self.peek("OR"):
            self.take("OR")
            right = self.conjunction()
            result = result or right
        return result

    def matches(self):
        """Require complete consumption so unsupported SQL cannot silently pass.

        Returns:
            bool: True if the entire expression evaluates to true for the row.

        Raises:
            AssertionError: If trailing unparsed tokens remain after evaluation.
        """
        # Empty predicate expressions match all rows unconditionally
        if not self.tokens:
            return True
        result = self.disjunction()
        # Verify parser reached end of token stream to prevent silent partial matches
        assert self.position == len(self.tokens), self.tokens[self.position :]
        return result


class Cursor:
    """Record real Oracle SQL and evaluate the supported metadata subset.

    Acts as an in-memory DB-API cursor substitute, intercepting INSERT, UPDATE,
    DELETE, and SELECT statements, mutating in-memory tables, and recording SQL
    for test assertions.
    """

    def __init__(self, connection):
        """Share the connection's transaction and statement recorder.

        Args:
            connection (Connection): Parent test Connection instance managing tables.
        """
        self.connection = connection
        self.description = None
        self.rows = []

    def __enter__(self):
        """Enter a DB-API cursor scope.

        Returns:
            Cursor: The current cursor instance.
        """
        return self

    def __exit__(self, *exc):
        """Finish the test cursor scope.

        Args:
            *exc (Any): Optional exception type, instance, and traceback tuple.

        Returns:
            None: Suppresses no exceptions.
        """

    def setinputsizes(self, **sizes: oracledb.DbType) -> None:
        """Record explicit Oracle CLOB binding declarations.

        Args:
            **sizes (oracledb.DbType): Oracle types keyed by SQL bind name.
        """
        # Track CLOB and BLOB driver input size hints for verification in unit tests
        self.connection.input_sizes.append(sizes)

    def execute(self, statement, parameters=None):
        """Evaluate only statements emitted by production metadata persistence.

        Args:
            statement (str): SQL query or DML statement to execute.
            parameters (dict[str, Any] | None): Optional bind parameters dictionary.

        Returns:
            Cursor: The cursor instance itself after statement processing.

        Raises:
            AssertionError: If the SQL format is unsupported by the test recorder.
            Exception: Re-raises constraint or syntax errors after state rollback.
        """
        sql = statement
        binds = parameters or {}
        # Record executed SQL and binds for assertion inspection in tests
        self.connection.statements.append((sql, dict(binds)))
        self.description = None
        self.rows = []
        # Fast path for Oracle connection validation probe
        if sql == "SELECT 1 FROM dual":
            self.rows = [(1,)]
            self.description = [("1",)]
            return self
        if sql.startswith("SELECT "):
            self.select(sql, binds)
            return self
        # Snapshot state prior to mutation to enable immediate rollback on error
        before = deepcopy(self.connection.tables)
        try:
            if match := re.fullmatch(r"INSERT INTO (\w+) \((.+)\) VALUES \((.+)\)", sql):
                match_groups = match.groups()
                table = match_groups[0]
                columns = match_groups[1]
                values = match_groups[2]
                col_names = columns.split(", ")
                val_items = values.split(", ")
                col_vals = [Predicate(val, binds, {}).value() for val in val_items]
                row = dict(self.connection.defaults[table])
                row.update(zip(col_names, col_vals, strict=True))
                self.connection.tables[table].append(row)
            elif match := re.fullmatch(r"UPDATE (\w+) SET (.+) WHERE (.+)", sql):
                match_groups = match.groups()
                table = match_groups[0]
                assignments = match_groups[1]
                where = match_groups[2]
                for row in self.connection.tables[table]:
                    if Predicate(where, binds, row).matches():
                        for assignment in assignments.split(", "):
                            assign_parts = assignment.split(" = ")
                            column = assign_parts[0]
                            value = assign_parts[1]
                            row[column] = Predicate(value, binds, row).value()
            elif match := re.fullmatch(r"DELETE FROM (\w+) WHERE (.+)", sql):
                match_groups = match.groups()
                table = match_groups[0]
                where = match_groups[1]
                current_rows = self.connection.tables[table]
                # Retain rows that do not match the DELETE WHERE clause predicate
                filtered_rows = [r for r in current_rows if not Predicate(where, binds, r).matches()]
                self.connection.tables[table] = filtered_rows
            else:
                raise AssertionError(f"Unsupported test SQL: {sql}")
            # Enforce schema foreign keys, uniqueness, and check constraints
            self.connection.validate()
        except Exception:
            # Revert mutation on constraint or processing failure
            self.connection.tables = before
            raise
        return self

    def select(self, sql, binds):
        """Apply Oracle predicates, ordering, grouping, and bound row limits.

        Args:
            sql (str): SELECT SQL query string to evaluate against in-memory tables.
            binds (dict[str, Any]): Dictionary of bind parameters.

        Raises:
            AssertionError: If the SELECT query structure is unsupported.
        """
        # Strip Oracle-specific locking and pagination clauses before evaluation
        sql = re.sub(r" FOR UPDATE(?: SKIP LOCKED)?$", "", sql)
        sql = re.sub(r" FETCH NEXT :row_limit ROWS ONLY$", "", sql)
        sql = re.sub(r" OFFSET :row_offset ROWS$", "", sql)
        base_pat = r"SELECT (.+?) FROM (\w+)(?: WHERE (.*?))?"
        select_pattern = base_pat + r"(?: GROUP BY (\w+))?(?: ORDER BY (.+))?"
        match = re.fullmatch(select_pattern, sql)
        assert match, f"Unsupported test SQL: {sql}"
        match_groups = match.groups()
        columns = match_groups[0]
        table = match_groups[1]
        where = match_groups[2]
        group = match_groups[3]
        order = match_groups[4]
        all_rows = self.connection.tables[table]
        if columns == "*":
            columns = ", ".join(all_rows[0]) if all_rows else ""
        rows = [row for row in all_rows if Predicate(where or "", binds, row).matches()]
        if order:
            for part in reversed(order.split(", ")):
                tokens = part.split()
                column = tokens[0]
                direction = tokens[1:]
                descending = direction == ["DESC"]
                rows.sort(key=lambda row: (row[column] is None, row[column]), reverse=descending)
        if group:
            assert columns == f"{group}, COUNT(*)"
            keys = dict.fromkeys(row[group] for row in rows)
            result = [(key, sum(row[group] == key for row in rows)) for key in keys]
        elif aggregate := re.fullmatch(r"(COUNT|SUM)\((\*|\w+)\)", columns):
            agg_groups = aggregate.groups()
            operation = agg_groups[0]
            column = agg_groups[1]
            if column != "*":
                values = [row[column] for row in rows if row[column] is not None]
            else:
                values = rows
            result = [(len(values) if operation == "COUNT" else sum(values) if values else None,)]

        else:
            result = [tuple(row[column] for column in columns.split(", ")) for row in rows]
        offset = binds.get("row_offset", 0)
        limit = binds.get("row_limit")
        self.rows = result[offset : offset + limit if limit is not None else None]
        self.description = [(column,) for column in columns.split(", ")]

    def fetchone(self):
        """Consume one detached row, matching the driver cursor contract."""
        return self.fetchmany(1)[0] if self.rows else None

    def fetchmany(self, size=None):
        """Consume a bounded result batch for streaming report tests."""
        count = size or getattr(self, "arraysize", 100)
        rows, self.rows = self.rows[:count], self.rows[count:]
        return deepcopy(rows)

    def fetchall(self):
        """Return detached result rows like a materialized driver response.

        Returns:
            list[tuple[Any, ...]]: Deep copy of buffered row tuples from the last query.
        """
        return deepcopy(self.rows)


class Connection:
    """Share a transactional Oracle statement test double across metadata sessions.

    Simulates table storage, primary key uniqueness, foreign key validation,
    NOT NULL checks, and CHECK constraints for all tables defined in migrations.
    """

    def __init__(self):
        """Read constraint declarations from the packaged Oracle schema."""
        self.tables = {}
        self.constraints = {}
        self.defaults = {}
        self.statements = []
        self.input_sizes = []
        for statement in schema_statements():
            match = re.match(r"CREATE TABLE (\w+)", statement)
            if not match:
                continue
            table = match[1]
            self.tables[table] = []
            self.defaults[table] = {name: Predicate(value, {}, {}).value() for name, value in re.findall(r"^\s+(\w+) [^\n]*?DEFAULT ('[^']*'|\d+)", statement, re.MULTILINE)}
            uniq_pat = r"(?:PRIMARY KEY|UNIQUE) \(([^)]+)\)"
            fk_pat = r"FOREIGN KEY \((\w+)\) REFERENCES (\w+) \((\w+)\)"
            req_pat = r"^\s+(\w+) [^\n]+NOT NULL"
            chk_pat = r"CHECK \((\w+ IN \([^)]+\))\)"
            table_constraints = {"unique": re.findall(uniq_pat, statement)}
            table_constraints["foreign"] = re.findall(fk_pat, statement)
            table_constraints["required"] = re.findall(req_pat, statement, re.MULTILINE)
            table_constraints["checks"] = re.findall(chk_pat, statement)
            self.constraints[table] = table_constraints
        self.saved = deepcopy(self.tables)

    def validate(self):
        """Check basic schema relationships and uniqueness without another SQL engine.

        Raises:
            oracledb.IntegrityError: If unique, not null, foreign key, or check constraints fail.
        """
        for item in self.constraints.items():
            table = item[0]
            constraints = item[1]
            rows = self.tables[table]
            for columns in constraints["unique"]:
                keys = [tuple(row[column] for column in columns.split(", ")) for row in rows]
                nonnull = [key for key in keys if all(value is not None for value in key)]
                if len(set(nonnull)) != len(nonnull):
                    raise oracledb.IntegrityError("Test metadata constraint violation")
            for row in rows:
                if any(row[column] is None for column in constraints["required"]):
                    raise oracledb.IntegrityError("Test metadata constraint violation")
                for ref in constraints["foreign"]:
                    column = ref[0]
                    parent = ref[1]
                    key = ref[2]
                    if row[column] is not None and not any(item[key] == row[column] for item in self.tables[parent]):
                        raise oracledb.IntegrityError("Test metadata constraint violation")
                if any(not Predicate(check, {}, row).matches() for check in constraints["checks"]):
                    raise oracledb.IntegrityError("Test metadata constraint violation")

    def cursor(self):
        """Open a statement-recording DB-API cursor.

        Returns:
            Cursor: New Cursor instance referencing this connection.
        """
        return Cursor(self)

    def commit(self):
        """Retain committed rows for later transaction scopes."""
        self.saved = deepcopy(self.tables)

    def rollback(self):
        """Discard changes since the last explicit commit."""
        self.tables = deepcopy(self.saved)

    def close(self):
        """Keep the fixture's shared statement store available across sessions."""

    def __enter__(self):
        """Return this raw test connection for fixture scopes."""
        return self

    def __exit__(self, *exc):
        """Discard uncommitted fixture work at scope exit."""
        try:
            self.rollback()
        finally:
            self.close()

    def acquire(self):
        """Return the fixture's raw connection for dependency injection."""
        return self


T = TypeVar("T", bound=BaseModel)


def bound_where(where: str, parameters: dict | None) -> tuple[str, dict]:
    """Expand collection placeholders into named binds, including empty collections.

    Args:
        where (str): SQL WHERE clause containing collection placeholders like {name}.
        parameters (dict | None): Dictionary of query bind parameters.

    Returns:
        tuple[str, dict]: Transformed WHERE clause with expanded binds and normalized dict.
    """
    # Clone bind parameters dictionary for in-place expansion of collection placeholders.
    binds = dict(parameters or {})
    for item in list(binds.items()):
        key = item[0]
        value = item[1]
        placeholder = "{" + key + "}"
        if placeholder not in where:
            continue
        del binds[key]
        values = sorted(value) if isinstance(value, (set, frozenset)) else list(value)
        names = []
        for enumerated in enumerate(values):
            index = enumerated[0]
            val_item = enumerated[1]
            name = f"{key}_{index}"
            names.append(":" + name)
            binds[name] = val_item
        in_list = ", ".join(names) or "NULL"
        where = where.replace(placeholder, f"({in_list})")
    # Coerce booleans to integer 0/1 for Oracle NUMBER(1) column compatibility.
    normalized_binds = {k: int(v) if isinstance(v, bool) else v for k, v in binds.items()}
    return where, normalized_binds


def execute(
    connection: oracledb.Connection,
    sql: str,
    parameters: dict | None = None,
    *,
    clobs: tuple[str, ...] = (),
) -> list[tuple]:
    """Execute caller-owned SQL and close its cursor without committing.

    Args:
        connection (oracledb.Connection): Caller-owned transaction.
        sql (str): Explicit SQL statement, optionally containing collection binds.
        parameters (dict | None): Bound values, never interpolated into SQL.
        clobs (tuple[str, ...]): Text parameters requiring Oracle CLOB binding.

    Returns:
        list[tuple]: Detached rows, with LOB locators read before cursor closure.
    """
    sql, binds = bound_where(sql, parameters)
    with connection.cursor() as cursor:
        if clobs:
            cursor.setinputsizes(**dict.fromkeys(clobs, oracledb.DB_TYPE_CLOB))
        cursor.execute(sql, binds)
        if not cursor.description:
            return []
        return [tuple(value.read() if hasattr(value, "read") else value for value in row) for row in cursor.fetchall()]


def fetch_records(connection: oracledb.Connection, model: type[T], sql: str, parameters: dict | None = None) -> list[T]:
    """Decode an explicit SELECT into detached Pydantic records.

    Args:
        connection (oracledb.Connection): Caller-owned transaction.
        model (type[T]): Record type matching the selected column names.
        sql (str): Complete caller-owned SELECT statement.
        parameters (dict | None): Bound query values.

    Returns:
        list[T]: Records with no identity cache or implicit persistence.
    """
    sql, binds = bound_where(sql, parameters)
    with connection.cursor() as cursor:
        cursor.execute(sql, binds)
        names = [column[0].lower() for column in cursor.description]
        records = []
        for row in cursor.fetchall():
            values = [value.read() if hasattr(value, "read") else value for value in row]
            records.append(model.model_validate(dict(zip(names, values, strict=True))))
        return records
